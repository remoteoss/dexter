// testBeam builds a compiled module that has only an atom table and an export
// table, which is all that the generated-function reader needs.
func testBeam(exports map[string][]int) []byte {
	be32 := func(buf *bytes.Buffer, v int) {
		var b [4]byte
		binary.BigEndian.PutUint32(b[:], uint32(v))
		buf.Write(b[:])
	}
	chunk := func(body *bytes.Buffer, name string, data []byte) {
		body.WriteString(name)
		be32(body, len(data))
		body.Write(data)
		for body.Len()%4 != 0 {
			body.WriteByte(0)
		}
	}
	names := []string{"Elixir.Minimal"}
	type export struct{ atom, arity int }
	var table []export
	for name, arities := range exports {
		names = append(names, name)
		for _, a := range arities {
			table = append(table, export{len(names), a})
		}
	}
	var atoms bytes.Buffer
	be32(&atoms, len(names))
	for _, n := range names {
		atoms.WriteByte(byte(len(n)))
		atoms.WriteString(n)
	}
	var exp bytes.Buffer
	be32(&exp, len(table))
	for i, e := range table {
		be32(&exp, e.atom)
		be32(&exp, e.arity)
		be32(&exp, i+1)
	}
	var body bytes.Buffer
	chunk(&body, "AtU8", atoms.Bytes())
	chunk(&body, "ExpT", exp.Bytes())
	var file bytes.Buffer
	file.WriteString("FOR1")
	be32(&file, body.Len()+4)
	file.WriteString("BEAM")
	file.Write(body.Bytes())
	return file.Bytes()
}

// A module with a function that `use` injects, a function that only the
// compiled module has (a macro made it), and a defdelegate.
func setupMembersProject(t *testing.T) *testEnv {
	t.Helper()
	e := setupProject(t)
	e.indexFile("lib/my_app/worker_base.ex", `defmodule MyApp.WorkerBase do
  defmacro __using__(_opts) do
    quote do
      @doc "Builds a job for this worker."
      def new(args, opts \\ []), do: {args, opts}
      defp secret(x), do: x
    end
  end
end
`)
	e.indexFile("lib/my_app/delivery.ex", "defmodule MyApp.Delivery do\n  def deliver(x), do: x\nend\n")
	e.indexFile("lib/my_app/mailer.ex", `defmodule MyApp.Mailer do
  use MyApp.WorkerBase

  def perform(job), do: job
  defdelegate deliver(x), to: MyApp.Delivery
end
`)
	ebin := filepath.Join(e.root, "_build", "dev", "lib", "my_app", "ebin")
	if err := os.MkdirAll(ebin, 0o755); err != nil {
		t.Fatal(err)
	}
	beamPath := filepath.Join(ebin, "Elixir.MyApp.Mailer.beam")
	if err := os.WriteFile(beamPath, testBeam(map[string][]int{
		"perform": {1}, "new": {1, 2}, "deliver": {1}, "generated_query": {1},
	}), 0o644); err != nil {
		t.Fatal(err)
	}
	// The compiled module is newer than the source, as after a build.
	later := time.Now().Add(time.Minute)
	if err := os.Chtimes(beamPath, later, later); err != nil {
		t.Fatal(err)
	}
	return e
}

// Regression: dexter_module_api did not list the functions that a `use`
// injects or that a macro generates, although dexter_definition finds them.
func TestModuleAPI_ListsInjectedAndGeneratedFunctions(t *testing.T) {
	e := setupMembersProject(t)

	api := e.callTool("dexter_module_api", map[string]any{"module": "MyApp.Mailer"})
	wantContains(t, api,
		"perform(job)",
		"deliver(x) [lib/my_app/mailer.ex:5] → MyApp.Delivery.deliver",
		"Injected or generated",
		"new(args) [lib/my_app/worker_base.ex:5] - injected by `use MyApp.WorkerBase` at lib/my_app/mailer.ex:2",
		"new(args, opts) [lib/my_app/worker_base.ex:5] - injected by `use MyApp.WorkerBase` at lib/my_app/mailer.ex:2",
		"Builds a job for this worker.",
		"generated_query(arg1) [lib/my_app/mailer.ex:1] - generated by a macro (compiled module)",
	)
	wantNotContains(t, api, "secret", "older than the source")

	// dexter_definition finds the same functions at the same places.
	wantContains(t, e.callTool("dexter_definition", map[string]any{"module": "MyApp.Mailer", "function": "new"}), "MyApp.Mailer.new/1 (def) - lib/my_app/worker_base.ex:5")
	wantContains(t, e.callTool("dexter_definition", map[string]any{"module": "MyApp.Mailer", "function": "generated_query"}), "lib/my_app/mailer.ex:1")
	wantContains(t, e.callTool("dexter_definition", map[string]any{"module": "MyApp.Mailer", "function": "deliver"}), "lib/my_app/mailer.ex:5", "Delegates to MyApp.Delivery.deliver")

	// dexter_search finds them by Module.function.
	search := e.callTool("dexter_search", map[string]any{"query": "MyApp.Mailer.new"})
	wantContains(t, search,
		"MyApp.Mailer.new/1 (def, injected by `use MyApp.WorkerBase` at lib/my_app/mailer.ex:2) - lib/my_app/worker_base.ex:5",
		"MyApp.Mailer.new/2",
	)
	wantContains(t, e.callTool("dexter_search", map[string]any{"query": "MyApp.Mailer.generated"}),
		"MyApp.Mailer.generated_query/1 (", "generated by a macro (compiled module)) - lib/my_app/mailer.ex:1")
}

// A compiled module older than the source can be out of date, and the answer
// says so.
func TestModuleAPI_MarksGeneratedFunctionsFromAnOldBuild(t *testing.T) {
	e := setupMembersProject(t)
	beamPath := filepath.Join(e.root, "_build", "dev", "lib", "my_app", "ebin", "Elixir.MyApp.Mailer.beam")
	earlier := time.Now().Add(-time.Hour)
	if err := os.Chtimes(beamPath, earlier, earlier); err != nil {
		t.Fatal(err)
	}
	api := e.callTool("dexter_module_api", map[string]any{"module": "MyApp.Mailer"})
	line := ""
	for _, l := range strings.Split(api, "\n") {
		if strings.Contains(l, "generated_query") {
			line = l
		}
	}
	wantContains(t, line, "older than the source")
}

// A use chain with an option value that Dexter cannot read gives the use line
// for a name that it can inject, and not for a typo.
func TestDefinition_UnknownOptionNameNotInjected(t *testing.T) {
	e := setupTestEnv(t)
	e.indexFile("lib/my_app/base.ex", "defmodule MyApp.Base do\n  defmacro __using__(_opts) do\n    quote do\n      def new(args), do: args\n    end\n  end\nend\n")
	e.indexFile("lib/my_app/wrapper.ex", "defmodule MyApp.Wrapper do\n  defmacro __using__(opts) do\n    {mod, _opts} = Keyword.pop(opts, :base, MyApp.Base)\n\n    quote do\n      use unquote(mod)\n    end\n  end\nend\n")
	e.indexFile("lib/my_app/worker.ex", "defmodule MyApp.Worker do\n  use MyApp.Wrapper, base: @base\nend\n")

	wantContains(t, e.callTool("dexter_definition", map[string]any{"module": "MyApp.Worker", "function": "new"}), "lib/my_app/worker.ex:2")
	typo := e.callTool("dexter_definition", map[string]any{"module": "MyApp.Worker", "function": "bogus"})
	wantContains(t, typo, "MyApp.Worker.bogus is not in the index")
	wantNotContains(t, typo, "lib/my_app/worker.ex:2")
}

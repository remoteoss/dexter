package mcp

import (
	"fmt"
	"strings"

	"github.com/remoteoss/dexter/internal/lsp"
)

// maxMembersShown caps the injected and generated functions that one answer
// lists. A compiled module can export hundreds (route helpers), and each one
// shown costs a definition lookup.
const maxMembersShown = 100

// memberOrigin describes where an injected or generated function comes from.
func (h *Handler) memberOrigin(module string, m lsp.ModuleMember) string {
	switch m.Source {
	case lsp.MemberInjected:
		origin := fmt.Sprintf("injected by `use %s`", m.UsedModule)
		if m.UseLine > 0 {
			if loc, ok := h.moduleFile(module); ok {
				origin += fmt.Sprintf(" at %s:%d", h.relPath(loc), m.UseLine)
			}
		}
		return origin
	default:
		origin := "generated by a macro (compiled module)"
		if m.StaleBeam {
			origin += "; the compiled module is older than the source, so this can be out of date"
		}
		return origin
	}
}

func (h *Handler) moduleFile(module string) (string, bool) {
	results, err := h.store.LookupModule(module)
	if err != nil || len(results) == 0 {
		return "", false
	}
	return results[0].FilePath, true
}

// memberLocation is where definition (LookupName) puts the member, so that
// the tools agree.
func (h *Handler) memberLocation(module string, m lsp.ModuleMember) string {
	locations, err := h.lsp.LookupName(module, m.Name, lsp.NameLookupOptions{External: true})
	if err == nil {
		for _, l := range locations {
			if l.Arity == m.Arity || l.Arity == 0 {
				return fmt.Sprintf("%s:%d", h.relPath(l.FilePath), l.Line)
			}
		}
		if len(locations) > 0 {
			return fmt.Sprintf("%s:%d", h.relPath(locations[0].FilePath), locations[0].Line)
		}
	}
	if m.FilePath != "" {
		return fmt.Sprintf("%s:%d", h.relPath(m.FilePath), m.Line)
	}
	return ""
}

func memberSignature(m lsp.ModuleMember) string {
	if m.Params != "" {
		return fmt.Sprintf("%s(%s)", m.Name, strings.ReplaceAll(m.Params, ",", ", "))
	}
	return fmt.Sprintf("%s/%d", m.Name, m.Arity)
}
